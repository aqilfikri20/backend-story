# Parse keyword user
# =========================
def parse_keywords(text):

    keywords = [
        x.strip().lower()
        for x in text.split(",")
        if x.strip()
    ]

    peran = []
    elemen = []
    sifat = []
    latar = []

    for word in keywords:

        if word in peran_list:
            peran.append(word)

        elif word in elemen_list:
            elemen.append(word)

        elif word in sifat_list:
            sifat.append(word)

        elif word in latar_list:
            latar.append(word)

        else:
            elemen.append(word)

    return keywords, peran, elemen, sifat, latar

# =========================
# Tambah relasi
# =========================
def apply_relations(keywords, peran, elemen, sifat, latar):

    for keyword in keywords:

        if keyword not in relations:
            continue

        rel = relations[keyword]

        # PERAN
        if not peran and "peran" in rel:

            value = weighted_pick(rel["peran"])

            if value and value not in peran:
                peran.append(value)

        # ELEMEN
        if "elemen" in rel:
            value = weighted_pick(rel["elemen"])

            if value and value not in elemen:
                elemen.append(value)

        # SIFAT
        if not sifat and "sifat" in rel:

            value = weighted_pick(rel["sifat"])

            if value and value not in sifat:
                sifat.append(value)

        # LATAR
        if not latar and "latar" in rel:

            value = weighted_pick(rel["latar"])

            if value and value not in latar:
                latar.append(value)

    return peran, elemen, sifat, latar
# =========================
# Fallback jika kosong
# =========================
def fill_missing(peran, elemen, sifat, latar):

    if not peran:
        peran.append(random.choice(list(peran_list)))

    if not elemen:
        elemen.append(random.choice(list(elemen_list)))

    if not sifat:
        sifat.append(random.choice(list(sifat_list)))

    if not latar:
        latar.append(random.choice(list(latar_list)))

    return peran, elemen, sifat, latar

